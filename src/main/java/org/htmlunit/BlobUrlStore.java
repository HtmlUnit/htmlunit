package org.htmlunit;

import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

import org.htmlunit.javascript.host.file.Blob;

/**
 * The user-agent-wide blob URL store defined by
 * <a href="https://w3c.github.io/FileAPI/#BlobURLStore">Blob URL Store</a>.
 *
 * @author Lai Quang Duong
 * @author Ronald Brill
 */
public class BlobUrlStore {

    private static final class Entry {
        private final Blob object_;
        private final Page owningPage_;

        Entry(final Blob object, final Page owningPage) {
            object_ = object;
            owningPage_ = owningPage;
        }
    }

    private final Map<String, Entry> store_ = new ConcurrentHashMap<>();

    /**
     * Adds an entry.
     *
     * <p>The {@code blobUrl} should not contain a fragment — fragments are
     * stripped when resolving and removing entries but not on insertion.
     * In practice this is always satisfied because blob URLs generated by
     * {@code URL.createObjectURL()} never carry a fragment.
     * </p>
     *
     * @param blobUrl the generated {@code blob:} URL; must not contain a fragment
     * @param object the {@link Blob} (or {@code File}) the URL refers to
     * @param owningPage the page that created the URL
     */
    public void put(final String blobUrl, final Blob object, final Page owningPage) {
        store_.put(blobUrl, new Entry(object, owningPage));
    }

    /**
     * Resolves a blob URL to its stored {@link Blob} object per
     * <a href="https://w3c.github.io/FileAPI/#blob-url-resolve">the Blob URL resolution algorithm</a>.
     *
     * <p>Note: this implementation resolves the URL regardless of which page or environment
     * is requesting it, which is a deliberate simplification of the spec's origin checks.
     * </p>
     *
     * <p>Any fragment component in {@code blobUrl} is ignored during lookup.</p>
     *
     * @param blobUrl the {@code blob:} URL to resolve
     * @return the stored {@link Blob}, or {@code null} if no entry exists for this URL
     */
    public Blob resolve(final String blobUrl) {
        final int fragmentIndex = blobUrl.indexOf('#');
        final String url = fragmentIndex >= 0 ? blobUrl.substring(0, fragmentIndex) : blobUrl;

        final Entry entry = store_.get(url);
        return entry == null ? null : entry.object_;
    }

    /**
     * Removes the entry for the given blob URL, revoking access to the associated {@link Blob}.
     *
     * @param blobUrl the {@code blob:} URL to revoke
     */
    public void remove(final String blobUrl) {
        store_.remove(blobUrl);
    }

    /**
     * Removes all blob URL entries associated with the given page.
     * Called when a page is unloaded to honour the
     * <a href="https://w3c.github.io/FileAPI/#lifeTime">blob URL lifetime</a> rules.
     *
     * <p>Note: this operation is not atomic — entries added concurrently during
     * page unload may survive. This is acceptable given HtmlUnit's single-threaded
     * page lifecycle.
     * </p>
     *
     * @param owningPage the page being unloaded
     */
    // package-private: called by the page lifecycle, not part of the public API
    void removeForPage(final Page owningPage) {
        store_.values().removeIf(entry -> entry.owningPage_ == owningPage);
    }

    /**
     * <span style="color:red">INTERNAL API - SUBJECT TO CHANGE AT ANY TIME - USE AT YOUR OWN RISK.</span><br>
     *
     * Removes all entries regardless of owning page.
     * Prefer {@link #removeForPage(Page)} for normal page lifecycle handling.
     */
    public void clear() {
        store_.clear();
    }
}
